inline bool IsListed(std::uint16_t unit)
{
    if (unit < 0xAC00 || unit > 0xD7A3)
        return false;
    std::uint16_t const offset = static_cast<std::uint16_t>(unit - 0xAC00);
    return ((BITMAP[offset / 64] >> (offset % 64)) & 1ULL) != 0;
}
